"""Pydantic v2 request and response schemas for CineBot."""

from __future__ import annotations

from typing import Literal, Optional

from pydantic import BaseModel, ConfigDict, Field


class ChatHistoryMessage(BaseModel):
    """Represents a single turn in the conversation history."""

    model_config = ConfigDict(extra="ignore")

    role: Literal["user", "assistant"] = Field(
        ...,
        description="Role of the message sender",
    )
    content: str = Field(
        ...,
        min_length=1,
        max_length=8000,
        description="Message text content",
    )


class FilterOptions(BaseModel):
    """Optional filters to narrow semantic movie search results."""

    model_config = ConfigDict(extra="ignore")

    genre: Optional[str] = Field(
        default=None,
        description="Optional genre filter (e.g., 'Sci-Fi', 'Action', 'Drama')",
    )
    min_rating: Optional[float] = Field(
        default=None,
        ge=0.0,
        le=10.0,
        description="Minimum TMDB rating (0.0 - 10.0)",
    )
    min_year: Optional[int] = Field(
        default=None,
        ge=1900,
        le=2030,
        description="Minimum release year",
    )


class MovieItem(BaseModel):
    """Schema for a recommended movie."""

    model_config = ConfigDict(from_attributes=True)

    id: int = Field(..., description="Unique movie identifier")
    title: str = Field(..., description="Movie title")
    overview: str = Field(..., description="Plot summary / overview")
    genres: list[str] = Field(default_factory=list, description="List of genres")
    release_year: Optional[int] = Field(default=None, description="Release year")
    release_date: Optional[str] = Field(default=None, description="Release date (YYYY-MM-DD)")
    vote_average: float = Field(default=0.0, description="Average TMDB rating (0-10)")
    popularity: float = Field(default=0.0, description="Popularity score")
    poster_url: Optional[str] = Field(default=None, description="URL to movie poster image")
    similarity_score: float = Field(
        default=0.0,
        description="Cosine similarity score from FAISS semantic search",
    )


class ChatRequest(BaseModel):
    """Incoming user chat & recommendation request payload."""

    model_config = ConfigDict(extra="ignore")

    message: str = Field(
        ...,
        min_length=1,
        max_length=1500,
        description="User's natural language query or movie preference",
        examples=["Inception tarzı zihin bükücü bilim kurgu filmleri önerir misin?"],
    )
    top_k: int = Field(
        default=5,
        ge=1,
        le=15,
        description="Number of recommendations to retrieve",
    )
    history: list[ChatHistoryMessage] = Field(
        default_factory=list,
        description="Recent conversation history for multi-turn context",
    )
    filters: Optional[FilterOptions] = Field(
        default=None,
        description="Optional metadata filters for recommendations",
    )
    previous_recommendations: list[MovieItem] = Field(
        default_factory=list,
        max_length=15,
        description="Films shown in the last assistant turn, so follow-up questions can refer to them",
    )


class ChatResponse(BaseModel):
    """Outgoing response containing LLM explanation and recommended movies."""

    model_config = ConfigDict(from_attributes=True)

    reply: str = Field(
        ...,
        description="Natural language response generated by the LLM",
    )
    recommendations: list[MovieItem] = Field(
        default_factory=list,
        description="List of semantically matched movies from FAISS",
    )
    query_used: str = Field(
        ...,
        description="Processed search query used for vector retrieval",
    )
    llm_provider: str = Field(
        default="template",
        description="Active provider that generated the response (groq, gemini, openai, or template)",
    )
    latency_ms: float = Field(
        default=0.0,
        description="End-to-end processing time in milliseconds",
    )
    follow_up: bool = Field(
        default=False,
        description="True when the reply answered a question about the previous recommendations instead of running a new search",
    )


class HealthResponse(BaseModel):
    """System readiness and health check response."""

    status: str = Field(default="ok")
    app_name: str
    dataset_loaded: bool
    total_movies: int
    embedding_model: str
    llm_provider: str
